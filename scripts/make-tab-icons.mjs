#!/usr/bin/env node
// Writes the tab bar's icon set into the Android project from
// icons/tab-icons.json: an outline drawable (unselected) and a filled one
// (selected) per icon, a selector that switches between them, and TabIcons.kt,
// which maps the names an app config uses to those drawables.
//
// The output is committed. Run this after changing the JSON:
//   node scripts/make-tab-icons.mjs          write the files
//   node scripts/make-tab-icons.mjs --check  fail if the committed files are stale

import { readFile, writeFile, readdir, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, "..");
const DRAWABLES = path.join(ROOT, "android/app/src/main/res/drawable");
const KOTLIN = path.join(ROOT, "android/app/src/main/java/app/site2app/shell/TabIcons.kt");

/** Shown for an icon name the set does not have. A filled dot, 200 units across. */
const FALLBACK = "M480-380q-42 0-71-29t-29-71q0-42 29-71t71-29q42 0 71 29t29 71q0 42-29 71t-71 29Z";

const HEADER = "<!-- Generated by scripts/make-tab-icons.mjs from icons/tab-icons.json. Do not edit. -->";

function vector(pathData) {
  return `<?xml version="1.0" encoding="utf-8"?>
${HEADER}
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
    <group android:translateY="960">
        <path
            android:fillColor="@android:color/white"
            android:pathData="${pathData}" />
    </group>
</vector>
`;
}

function selector(name) {
  return `<?xml version="1.0" encoding="utf-8"?>
${HEADER}
<selector xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:drawable="@drawable/tab_${name}_fill" android:state_checked="true" />
    <item android:drawable="@drawable/tab_${name}_outline" />
</selector>
`;
}

function kotlin(names) {
  const entries = names.map((name) => `        "${name}" to R.drawable.tab_${name},`).join("\n");
  return `// Generated by scripts/make-tab-icons.mjs from icons/tab-icons.json. Do not edit.
package app.site2app.shell

/** The tab bar's built-in icons, by the name an app config uses. */
internal object TabIcons {
    private val icons = mapOf(
${entries}
    )

    val names: Set<String> get() = icons.keys

    /** The icon for [name]; a plain dot for a name the set does not have. */
    fun drawable(name: String): Int = icons[name] ?: R.drawable.tab_dot
}
`;
}

export async function expectedFiles() {
  const set = JSON.parse(await readFile(path.join(ROOT, "icons/tab-icons.json"), "utf8"));
  if (set.viewBox !== "0 -960 960 960") throw new Error(`Unexpected viewBox ${set.viewBox}`);
  const names = Object.keys(set.icons);
  const files = new Map();
  for (const name of names) {
    if (!/^[a-z][a-z0-9]*$/.test(name)) throw new Error(`Icon name "${name}" is not a valid resource name`);
    const { outline, fill } = set.icons[name];
    files.set(path.join(DRAWABLES, `tab_${name}_outline.xml`), vector(outline));
    files.set(path.join(DRAWABLES, `tab_${name}_fill.xml`), vector(fill));
    files.set(path.join(DRAWABLES, `tab_${name}.xml`), selector(name));
  }
  files.set(path.join(DRAWABLES, "tab_dot.xml"), vector(FALLBACK));
  files.set(KOTLIN, kotlin(names));
  return files;
}

async function main() {
  const check = process.argv.includes("--check");
  const files = await expectedFiles();
  const stale = [];
  for (const [file, text] of files) {
    const current = await readFile(file, "utf8").catch(() => null);
    if (current === text) continue;
    if (check) stale.push(path.relative(ROOT, file));
    else await writeFile(file, text);
  }
  // Drawables for icons that left the set.
  for (const name of await readdir(DRAWABLES)) {
    const file = path.join(DRAWABLES, name);
    if (!name.startsWith("tab_") || files.has(file)) continue;
    if (check) stale.push(path.relative(ROOT, file));
    else await rm(file);
  }
  if (check && stale.length > 0) {
    console.error(`Tab icons are out of date. Run node scripts/make-tab-icons.mjs:\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log(check ? "Tab icons are up to date." : `Wrote ${files.size} files.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) await main();
